import XCTest
@testable import RadioCrestinTV

/// tvOS rule: the word LIVE belongs to TV stations only. A radio station
/// whose backend `now_playing` name is the literal placeholder "LIVE" must
/// not surface it as a song title anywhere.
final class SongTitlePlaceholderTests: XCTestCase {

    private func station(
        songName: String?, kind: String = "radio"
    ) -> Station {
        Station(
            id: 1, slug: "s", title: "S", order: 0,
            thumbnailUrl: nil, totalListeners: nil,
            stationStreams: [],
            uptime: nil,
            nowPlaying: songName.map {
                NowPlaying(
                    id: 1, timestamp: nil,
                    song: Song(id: 1, name: $0, thumbnailUrl: nil, artist: nil)
                )
            },
            reviewsStats: nil,
            stationType: kind, playlistItems: nil, hlsDvrStreamUrl: nil
        )
    }

    func test_literal_live_placeholder_is_not_a_song_title() {
        XCTAssertEqual(station(songName: "LIVE").songTitle, "")
        XCTAssertEqual(station(songName: " live ").songTitle, "")
        XCTAssertEqual(station(songName: "Live Stream").songTitle, "")
    }

    func test_other_placeholders_are_suppressed_too() {
        for raw in ["n/a", "-", "unknown", "Necunoscut", "untitled"] {
            XCTAssertEqual(station(songName: raw).songTitle, "",
                           "\(raw) should be suppressed")
        }
    }

    func test_a_radio_card_never_shows_the_live_placeholder() {
        XCTAssertEqual(station(songName: "LIVE").cardSubtitle, "")
    }

    func test_real_song_titles_containing_live_survive() {
        XCTAssertEqual(
            station(songName: "Chemat-ai Azi Numele (Live)").songTitle,
            "Chemat-ai Azi Numele (Live)"
        )
        XCTAssertEqual(station(songName: "Living Hope").songTitle, "Living Hope")
    }

    func test_absent_now_playing_yields_an_empty_title() {
        XCTAssertEqual(station(songName: nil).songTitle, "")
    }

    func test_tv_stations_still_get_their_live_descriptor() {
        // The TV label is generated by the app, not by now_playing, so the
        // placeholder filter must not touch it.
        XCTAssertEqual(
            station(songName: "LIVE", kind: "tv").cardSubtitle,
            "Transmisiune live"
        )
    }
}
